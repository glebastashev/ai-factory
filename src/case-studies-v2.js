export function calculateCaseEffect(n) {
  if (n.type === 'sales') return Math.round(n.volume * (n.targetConversion - n.baseConversion) * n.margin - n.runningCost);
  if (n.type === 'documents') return Math.round(n.volume * (n.beforeUnitCost - n.afterUnitCost - n.pagesPerDocument * n.pageCost) - n.maintenance);
  if (n.type === 'project') return Math.round((n.beforeHours - n.afterHours) * n.hourlyRate - n.tools);
  return Math.round(n.volume * n.beforeUnitCost - n.manualVolume * n.afterUnitCost - n.runningCost);
}

function model(data) {
  const effect = calculateCaseEffect(data.calculation);
  const oneOff = data.calculation.type === 'project';
  return {
    ...data, effect,
    ...(oneOff ? {} : { monthlyEffect: effect }),
    metric: `${new Intl.NumberFormat('ru-RU').format(effect)} ₽`,
    period: oneOff ? '/ проект' : '/ мес.',
    calculationPeriod: oneOff ? 'Допущения для одного проекта' : 'Допущения для расчёта за один месяц',
    resultLabel: oneOff ? 'разница в затратах на один проект' : 'месячный эффект после текущих затрат',
    calculationNote: oneOff
      ? 'Сравнение затрат на одинаковый объём работ. Это пример бюджета, а не тариф агентства.'
      : 'Эффект до налогов. Разовые затраты на внедрение считаются отдельно после согласования объёма работ.',
  };
}

